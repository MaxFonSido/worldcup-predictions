const dict: Record<Lang, Dict> = { en, fa };

export function getLang(): Lang {
  const c = cookies().get("lang")?.value;
  return c === "fa" ? "fa" : "en";
}

export function t(lang: Lang): Dict {
  return dict[lang];
}

export function dir(lang: Lang): "rtl" | "ltr" {
  return lang === "fa" ? "rtl" : "ltr";
}
